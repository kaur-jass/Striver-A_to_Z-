// Data types in C++
#include<bits/stdc++.h>     // This header file includes all the standard libraries
using namespace std;
int main()
{
    // This program is used to take input from the user and print it on the console
    int x = 5; // int 
    cout << x << endl; // cout is used to print the output to the console 
    // long 
    long y = 15;
    cout<< y << endl;
    // long long
    long long z = 150000000000;
    cout << z << endl;
    // float 
    float a = 5.5;
    cout << a << endl;
    // double
    double b = 5.555555555555;
    cout << b << endl;
    // char
    char c = 'a';
    cout << c << endl;
    // string
    string d = "Hello World";
    cout << d << endl;
    return 0;
}