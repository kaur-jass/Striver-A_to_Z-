/*Time complexity and space complexity are ways to analyze how efficient an algorithm is in terms of:

Time complexity: How much time an algorithm takes to run as the input size increases.

Space complexity: How much memory (space) an algorithm uses as the input size increases.*/


/* 
🕒 Time Complexity
It tells how the runtime of an algorithm grows with the input size n.

Common Time Complexities:
Notation	         Meaning	                                  Example
O(1)	        Constant time (independent of input)     	Accessing an array element
O(log n)	    Logarithmic time	                        Binary search
O(n)	        Linear time	                                Loop through an array
O(n log n)	    Log-linear time	                            Merge sort, quicksort (avg)
O(n²)	        Quadratic time	                            Nested loops
O(2ⁿ), O(n!)	Exponential and factorial time	            Recursive solutions (bad)

*/


/* 
)

💾 Space Complexity
It tells how much extra memory is needed by an algorithm relative to the input size.

Includes:

Temporary variables

Stack space for recursion

Data structures used

Common Examples:
Space Complexity	Example
O(1)	            Uses fixed memory regardless of input
O(n)	            Storing elements in a new array
O(n²)	            Using 2D matrix (e.g., dynamic programming)
*/


